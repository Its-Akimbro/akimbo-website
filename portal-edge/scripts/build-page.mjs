// Builds the outage page's assets into build/page-assets.ts, which the Worker
// imports: Tailwind CSS from page/outage.css with the brand fonts inlined as
// data: URLs, and the brand lockup as a data: URL.
//
// Everything is inlined because the page is shown exactly when the portal is
// unreachable, and it must not depend on any other request succeeding.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const brand = join(root, "..", "brand");
const out = join(root, "build");
mkdirSync(out, { recursive: true });

const cssFile = join(out, "outage.css");
execFileSync(
  join(root, "node_modules", ".bin", "tailwindcss"),
  ["--input", join(root, "page", "outage.css"), "--output", cssFile, "--minify"],
  { cwd: root, stdio: ["ignore", "ignore", "inherit"] },
);

/** @param {string} type @param {string} file */
const dataUrl = (type, file) => `data:${type};base64,${readFileSync(file).toString("base64")}`;

let css = readFileSync(cssFile, "utf8")
  // The page sets no code, so the monospace face would be dead weight.
  .replace(/@font-face\{[^}]*jetbrains-mono[^}]*\}/g, "");
css = css.replace(/url\((["']?)\.\/fonts\/([\w.-]+\.woff2)\1\)/g, (_match, _quote, /** @type {string} */ name) =>
  `url(${dataUrl("font/woff2", join(brand, "fonts", name))})`,
);
if (/url\((?!data:)/.test(css)) {
  throw new Error("build-page: the outage CSS still references a file; inline it.");
}

const lockup = dataUrl("image/png", join(brand, "lockup-colour-for-dark-bg.png"));

writeFileSync(
  join(out, "page-assets.ts"),
  [
    "// Generated by scripts/build-page.mjs. Don't edit.",
    `export const PAGE_CSS = ${JSON.stringify(css)};`,
    `export const LOCKUP_SRC = ${JSON.stringify(lockup)};`,
    "",
  ].join("\n"),
);
console.log(`build-page: build/page-assets.ts (${Math.round((css.length + lockup.length) / 1024)} KiB)`);
